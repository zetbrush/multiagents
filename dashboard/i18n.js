/** Translate a captured fragment when it is itself a known phrase. */
function tz(s) {
  if (LANG !== "zh") return s;
  return ZH[s] ?? matchRule(s) ?? s;
}

function matchRule(s) {
  for (const [re, fn] of RULES_ZH) {
    const m = re.exec(s);
    if (m) return fn(m);
  }
  return null;
}

/**
 * Translate `en` into the current language and fill in `{name}` placeholders.
 * Unknown strings come back unchanged (in English).
 */
function tr(en, vars) {
  let s = en == null ? "" : String(en);
  if (LANG === "zh" && s) s = ZH[s] ?? matchRule(s) ?? s;
  if (vars) s = s.replace(/\{(\w+)\}/g, (all, k) => (k in vars ? String(vars[k] ?? "") : all));
  return s;
}

// --- Static markup: text nodes and title / placeholder / aria-label ---

const I18N_ATTRS = ["title", "placeholder", "aria-label"];
const textOrigin = new WeakMap(); // text node → { en, shown }
let staticNodes = null;

/**
 * Translate the page's own markup. The first call (at boot, before app code
 * renders anything) records which nodes are static; later calls re-translate
 * only those, so names and file paths rendered since are never touched.
 */
function translateStatic() {
  if (!staticNodes) {
    staticNodes = { text: collectText(document.body), els: [...document.body.querySelectorAll(I18N_ATTRS.map((a) => `[${a}]`).join(","))] };
  }
  for (const n of staticNodes.text) if (n.isConnected) translateText(n);
  for (const el of staticNodes.els) if (el.isConnected) translateAttrs(el);
}

/** Translate a freshly built subtree (modal bodies). */
function translateTree(root) {
  if (!root) return;
  for (const n of collectText(root)) translateText(n);
  for (const el of [root, ...root.querySelectorAll(I18N_ATTRS.map((a) => `[${a}]`).join(","))]) translateAttrs(el);
}

function collectText(root) {
  const nodes = [];
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode: (n) => {
      const p = n.parentElement;
      if (!p || p.closest("script, style, code, pre, textarea, .mono, [data-no-i18n]")) return NodeFilter.FILTER_REJECT;
      return /[A-Za-z]/.test(n.nodeValue) || textOrigin.has(n) ? NodeFilter.FILTER_ACCEPT : NodeFilter.FILTER_REJECT;
    },
  });
  for (let n = walker.nextNode(); n; n = walker.nextNode()) nodes.push(n);
  return nodes;
}

function translateText(n) {
  let rec = textOrigin.get(n);
  // Text that changed since we last translated it was set by app code: start over
  if (!rec || rec.shown !== n.nodeValue) { rec = { en: n.nodeValue }; textOrigin.set(n, rec); }
  const key = rec.en.trim();
  const out = key ? rec.en.replace(key, () => tr(key)) : rec.en;
  if (out !== n.nodeValue) n.nodeValue = out;
  rec.shown = n.nodeValue;
}

function translateAttrs(el) {
  for (const a of I18N_ATTRS) {
    const v = el.getAttribute(a);
    if (v == null) continue;
    const k = `i18n${a.replace(/-./g, (x) => x[1].toUpperCase()).replace(/^./, (x) => x.toUpperCase())}`;
    // Remember the English original; a value set since then replaces it
    if (el.dataset[k] === undefined || el.dataset[`${k}Shown`] !== v) el.dataset[k] = v;
    const out = tr(el.dataset[k]);
    if (out !== v) el.setAttribute(a, out);
    el.dataset[`${k}Shown`] = out;
  }
}
